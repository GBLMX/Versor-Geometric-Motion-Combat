"""Animate the Riemann zeta trajectory on the critical line.

The data is generated by ``bridge_data/zeta.wls``; this scene only reads the
flat record and moves a dot along the ``Re/Im`` path.
"""

import math
import os

import numpy as np
from manimlib import *

from versor_ga import KDE
from versor_ga.bridge import build_mobject, load_records

HERE = os.path.dirname(os.path.abspath(__file__))
RECORDS = load_records(os.path.join(HERE, "bridge_data", "data", "zeta.json"))
ZETA = next(record for record in RECORDS if record["id"] == "zeta_critical")
POINTS = ZETA["points"]


class ZetaScene(Scene):
    def construct(self):
        self.camera.background_color = KDE.background

        axes = Axes(
            x_range=(-2, 4, 1),
            y_range=(-2.5, 2.5, 1),
            width=9,
            height=7.5,
            axis_config=dict(stroke_color=KDE.axes, stroke_width=2),
        )
        axes.to_edge(DOWN, buff=0.35)
        re_label = Text("Re", font_size=28, color=KDE.text).next_to(
            axes.get_x_axis().get_end(), RIGHT, buff=0.12
        )
        im_label = Text("Im", font_size=28, color=KDE.text).next_to(
            axes.get_y_axis().get_end(), UP, buff=0.12
        )

        title = Text(
            "Riemann zeta on the critical line",
            font_size=34,
            color=KDE.command,
        ).to_edge(UP, buff=0.28)
        subtitle = Text(
            "zeta(1/2 + i t),  t = 0 .. 50",
            font_size=20,
            color=KDE.comment,
        ).next_to(title, DOWN, buff=0.08)

        self.play(
            ShowCreation(axes),
            FadeIn(re_label),
            FadeIn(im_label),
            FadeIn(title),
            FadeIn(subtitle),
            run_time=0.8,
        )

        curve = build_mobject(ZETA, axes)
        self.play(ShowCreation(curve), run_time=2.5)

        progress = ValueTracker(0.0)

        def sample(progress_value: float) -> np.ndarray:
            position = min(1.0, max(0.0, progress_value)) * (len(POINTS) - 1)
            lower = int(math.floor(position))
            upper = min(lower + 1, len(POINTS) - 1)
            fraction = position - lower
            p0 = np.asarray(POINTS[lower][1:], dtype=float)
            p1 = np.asarray(POINTS[upper][1:], dtype=float)
            return p0 * (1.0 - fraction) + p1 * fraction

        def sample_t(progress_value: float) -> float:
            index = min(len(POINTS) - 1, int(progress_value * (len(POINTS) - 1)))
            return float(POINTS[index][0])

        dot = Dot(axes.c2p(*sample(0.0)), radius=0.075, color=KDE.point)
        dot.add_updater(lambda mob: mob.move_to(axes.c2p(*sample(progress.get_value()))))

        t_caption = Text("t =", font_size=28, color=KDE.text).to_corner(UR, buff=0.4)
        t_value = DecimalNumber(
            sample_t(0.0),
            num_decimal_places=2,
            font_size=28,
            color=KDE.number,
        ).next_to(t_caption, DOWN, buff=0.08, aligned_edge=RIGHT)
        t_value.add_updater(lambda mob: mob.set_value(sample_t(progress.get_value())))

        self.play(FadeIn(dot), FadeIn(t_caption), FadeIn(t_value))
        self.play(progress.animate.set_value(1.0), run_time=12.0, rate_func=linear)
        self.wait(1.0)
